#include "aht20_decode.h"

#define AHT20_STATUS_BUSY   0x80
#define AHT20_STATUS_CAL    0x08

uint8_t AHT20_CRC8(const uint8_t *data, uint8_t len)
{
    uint8_t crc = 0xFF;
    for (uint8_t i = 0; i < len; i++)
    {
        crc ^= data[i];
        for (uint8_t j = 0; j < 8; j++)
            crc = (crc & 0x80) ? (uint8_t)((crc << 1) ^ 0x31) : (uint8_t)(crc << 1);
    }
    return crc;
}

AHT20_DecodeStatus AHT20_DecodeFrame(const uint8_t *buf,
                                     float *temp_out, float *hum_out)
{
    if ((buf[0] & AHT20_STATUS_BUSY) != 0)
        return AHT20_DEC_ERR_BUSY;

    uint32_t raw_hum = ((uint32_t)buf[1] << 12) |
                       ((uint32_t)buf[2] << 4)  |
                       ((uint32_t)buf[3] >> 4);

    uint32_t raw_temp = (((uint32_t)buf[3] & 0x0F) << 16) |
                        ((uint32_t)buf[4] << 8) |
                        ((uint32_t)buf[5]);

    /* Оба поля в нуле разом — типовой вид кадра от некалиброванного датчика.
     * Отдельный код возврата нужен вызывающему: ждать тут нечего, повторное
     * чтение вернёт те же байты, лечится только переинициализацией.
     * Проверка стоит до CRC: каким бы ни пришёл контрольный байт пустого
     * кадра, повторять измерение бессмысленно. */
    if (raw_temp == 0 && raw_hum == 0)
        return AHT20_DEC_ERR_ZERO;

    /* Шкала ловит не всё: внутрь -40..+85 попадает 62 % всего сырого
     * диапазона температуры, а влажность шкалой не проверить вовсе. Полуиспорченный
     * кадр с правдоподобными числами отличает только CRC по шести байтам. */
    if (AHT20_CRC8(buf, AHT20_FRAME_LEN - 1) != buf[AHT20_FRAME_LEN - 1])
        return AHT20_DEC_ERR_CRC;

    /* Кадр целый, но датчик сам говорит, что не откалиброван: его числа —
     * не измерение. Повтор тут не поможет, как и при пустом кадре. */
    if ((buf[0] & AHT20_STATUS_CAL) == 0)
        return AHT20_DEC_ERR_NOCAL;

    /* Кадр может испортиться и наполовину: в чистом 25-часовом прогоне
     * 24 августа один замер пришёл с raw_temp == 0 и живой на вид влажностью
     * 0.79 %. Проверка "оба поля в нуле" его пропустила, и в архив ушли
     * -50.00 °C — ровно тот же класс ошибки, ради которого модуль и заводился.
     *
     * Поэтому судим не по нулям, а по шкале самого датчика: сырая температура
     * раскладывается на -50..+150 °C, а измерять AHT20 умеет только -40..+85.
     * Значение за этими границами датчик выдать не может, значит кадр битый.
     * Сравнение в сырых единицах, а не в градусах: так граница — точное целое,
     * и её не сдвинет округление float.
     *
     * Ровный ноль сырой влажности — зеркальный случай того же инцидента:
     * в теплице датчик его не выдаёт, а вот обнулённые байты 1..3 выдают.
     *
     * Отвергается кадр целиком, а не одно поле: если одна половина мусор,
     * второй верить тоже нельзя — в той строке влажность 0.79 % стояла между
     * 53 % часом раньше и 50 % часом позже. */
    if (raw_hum == 0 ||
        raw_temp < AHT20_RAW_TEMP_MIN || raw_temp > AHT20_RAW_TEMP_MAX)
        return AHT20_DEC_ERR_RANGE;

    *hum_out  = (raw_hum * 100.0f) / 1048576.0f;
    *temp_out = (raw_temp * 200.0f / 1048576.0f) - 50.0f;

    return AHT20_DEC_OK;
}
