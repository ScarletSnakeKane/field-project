#include "aht20_decode.h"

#define AHT20_STATUS_BUSY   0x80

AHT20_DecodeStatus AHT20_DecodeFrame(const uint8_t *buf,
                                     float *temp_out, float *hum_out)
{
    if ((buf[0] & AHT20_STATUS_BUSY) != 0)
        return AHT20_DEC_ERR_BUSY;

    uint32_t raw_hum = ((uint32_t)buf[1] << 12) |
                       ((uint32_t)buf[2] << 4)  |
                       ((uint32_t)buf[3] >> 4);

    uint32_t raw_temp = (((uint32_t)buf[3] & 0x0F) << 16) |
                        ((uint32_t)buf[4] << 8) |
                        ((uint32_t)buf[5]);

    /* Оба поля в нуле разом — типовой вид кадра от некалиброванного датчика.
     * Отдельный код возврата нужен вызывающему: ждать тут нечего, повторное
     * чтение вернёт те же байты, лечится только переинициализацией. */
    if (raw_temp == 0 && raw_hum == 0)
        return AHT20_DEC_ERR_ZERO;

    float hum  = (raw_hum * 100.0f) / 1048576.0f;
    float temp = (raw_temp * 200.0f / 1048576.0f) - 50.0f;

    /* Кадр может испортиться и наполовину: в чистом 25-часовом прогоне
     * 24 августа один замер пришёл с raw_temp == 0 и живой на вид влажностью
     * 0.79 %. Проверка "оба поля в нуле" его пропустила, и в архив ушли
     * -50.00 °C — ровно тот же класс ошибки, ради которого модуль и заводился.
     *
     * Поэтому судим не по нулям, а по шкале самого датчика: сырая температура
     * раскладывается на -50..+150 °C, а измерять AHT20 умеет только -40..+85.
     * Значение за этими границами датчик выдать не может, значит кадр битый.
     * Влажность проверять нечем и незачем: raw_hum/2^20*100 по построению
     * лежит в 0..100, то есть всегда внутри шкалы.
     *
     * Отвергается кадр целиком, а не одно поле: если одна половина мусор,
     * второй верить тоже нельзя — в той строке влажность 0.79 % стояла между
     * 53 % часом раньше и 50 % часом позже. */
    if (temp < AHT20_TEMP_MIN_C || temp > AHT20_TEMP_MAX_C)
        return AHT20_DEC_ERR_RANGE;

    *hum_out  = hum;
    *temp_out = temp;

    return AHT20_DEC_OK;
}
