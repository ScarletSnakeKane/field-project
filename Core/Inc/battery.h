#ifndef BATTERY_H
#define BATTERY_H

#include "adc.h"

/* Делитель напряжения батареи заведён на PA2 = ADC1_IN2.
 * BAT_DIVIDER_RATIO = (R_верх + R_нижн) / R_нижн.
 *
 * Сейчас на плате 10к + 10к, то есть 20 кОм поперёк банки: это ~200 мкА
 * непрерывной утечки при бюджете ~300 мкА на год работы. Замена на 100к + 100к
 * даёт те же 2.0 и снижает утечку до ~21 мкА — коэффициент менять не придётся,
 * время выборки ниже уже взято с запасом под высокоомный источник. */
#define BAT_DIVIDER_RATIO   2.0f

/* Ниже этого напряжения XC6206 выходит из режима стабилизации: VDD начинает
 * следовать за банкой, и опорное напряжение АЦП уплывает вместе с ним.
 * Показания влажности почвы с этого момента считаем недостоверными. */
#define BAT_LOW_VOLTS       3.30f

typedef struct {
    float   volts;     /* напряжение банки */
    float   vdd;       /* реальное VDD, вычисленное через VREFINT */
    uint8_t percent;   /* заряд, % по кривой разряда Li-ion */
    uint8_t low;       /* 1 — ниже BAT_LOW_VOLTS */
    uint8_t valid;     /* 0 — измерить не удалось */
} Battery_Data;

/* Измеряет банку и вычисляет реальное VDD по внутреннему опорному источнику.
 * Возвращает 1 при успехе. */
uint8_t Battery_Read(Battery_Data *out);

#endif
