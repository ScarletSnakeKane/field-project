#ifndef POWER_POLICY_H
#define POWER_POLICY_H

/* Решения, от которых зависит поведение прибора в поле, — отдельно от HAL.
 *
 * Каждое выглядит как одна строка условия, и каждое уже успело повести себя
 * не так, как задумывалось: кнопочный жест стирал архив при любом аппаратном
 * сбросе (теперь его нет вовсе — архив стирают только с компьютера по USB),
 * таймер залипшей кнопки рвал USB-сессию. Ошибка здесь проявляется редко и
 * молча — данные исчезают или батарея садится, — поэтому правила вынесены
 * сюда и закреплены тестами.
 */

#include <stdint.h>

/* Держит ли зажатая KEY плату бодрствующей.
 *
 * Удержание кнопки не даёт уснуть — так владелец держит USB-сессию или ловит
 * окно для программатора. Потолок hold_max_ms нужен на случай залипшей или
 * залитой водой кнопки: без него прибор не уснул бы никогда.
 *
 * Раньше потолок отсчитывался заново при каждом входе в цикл удержания, то
 * есть действовал на один цикл: залипшая кнопка держала плату по 5 минут
 * КАЖДЫЙ час (~0.8 мА в среднем при бюджете 0.38 мА), а снаружи это не было
 * видно ничем (A1). Поэтому состояние хранится снаружи, между циклами сна,
 * и сбрасывается только тогда, когда кнопку увидели отпущенной. Признанная
 * залипшей кнопка бодрствования больше не продлевает, пока её не отпустят.
 *
 * dt_ms — сколько прошло с прошлого вызова (в первом вызове цикла — 0).
 * Возвращает 1, если из-за кнопки спать нельзя. */
typedef struct {
    uint8_t  stuck;     /* потолок исчерпан — кнопка залипла, ждём отпускания */
    uint32_t held_ms;   /* сколько длится текущее удержание, через все циклы */
} Policy_Button;

uint8_t Policy_ButtonKeepsAwake(Policy_Button *b, uint8_t key_held,
                                uint32_t dt_ms, uint32_t hold_max_ms);

#endif
