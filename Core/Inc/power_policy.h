#ifndef POWER_POLICY_H
#define POWER_POLICY_H

/* Решения, от которых зависит поведение прибора в поле, — отдельно от HAL.
 *
 * Каждое выглядит как одна строка условия, и каждое уже успело повести себя
 * не так, как задумывалось: кнопочный жест стирал архив при любом аппаратном
 * сбросе (теперь его нет вовсе — архив стирают только с компьютера по USB),
 * таймер залипшей кнопки рвал USB-сессию. Ошибка здесь проявляется редко и
 * молча — данные исчезают или батарея садится, — поэтому правила вынесены
 * сюда и закреплены тестами.
 */

#include <stdint.h>

/* Держит ли зажатая KEY плату бодрствующей.
 *
 * Удержание кнопки не даёт уснуть — так владелец держит USB-сессию или ловит
 * окно для программатора. Потолок hold_max_ms нужен на случай залипшей или
 * залитой водой кнопки: без него прибор не уснул бы никогда.
 *
 * Раньше потолок отсчитывался заново при каждом входе в цикл удержания, то
 * есть действовал на один цикл: залипшая кнопка держала плату по 5 минут
 * КАЖДЫЙ час (~0.8 мА в среднем при бюджете 0.38 мА), а снаружи это не было
 * видно ничем (A1). Поэтому состояние хранится снаружи, между циклами сна,
 * и сбрасывается только тогда, когда кнопку увидели отпущенной. Признанная
 * залипшей кнопка бодрствования больше не продлевает, пока её не отпустят.
 *
 * dt_ms — сколько прошло с прошлого вызова (в первом вызове цикла — 0).
 * Возвращает 1, если из-за кнопки спать нельзя. */
typedef struct {
    uint8_t  stuck;     /* потолок исчерпан — кнопка залипла, ждём отпускания */
    uint32_t held_ms;   /* сколько длится текущее удержание, через все циклы */
} Policy_Button;

uint8_t Policy_ButtonKeepsAwake(Policy_Button *b, uint8_t key_held,
                                uint32_t dt_ms, uint32_t hold_max_ms);
/* Держит ли USB плату бодрствующей (A9/C8).
 *
 * Раньше хватало уровня VBUS: пока он высокий, плата не спала вовсе. Но VBUS
 * без хоста — это USB-зарядка, пауэрбанк или влага на делителе, и тогда
 * прибор неделями бодрствовал на ~10 мА и не писал ни строки. Теперь VBUS
 * держит плату, только пока хост её перечислил (CONFIGURED), а без этого —
 * не дольше enum_max_ms. Не дождались — считаем VBUS зарядкой и спим по
 * обычному циклу; в следующих пробуждениях USB не поднимаем вовсе, пока VBUS
 * не пропадёт или не появится заново (vbus_edge — EXTI по фронту VBUS:
 * кабель вставили, значит это новый шанс перечислиться).
 *
 * Хост, перечисливший плату, держит её сколько угодно: она питается от него,
 * а уход в STOP оборвал бы чтение. Хост, который потом ушёл в сон (SUSPENDED),
 * снова отсчитывает enum_max_ms.
 * Возвращает 1, если из-за USB спать нельзя. */
typedef struct {
    uint32_t unconfigured_ms;   /* сколько VBUS есть, а хоста нет — через все циклы */
} Policy_Usb;

uint8_t Policy_UsbKeepsAwake(Policy_Usb *u, uint8_t usb_present, uint8_t usb_configured,
                             uint8_t vbus_edge, uint32_t dt_ms, uint32_t enum_max_ms);

/* Пора ли делать очередной замер, не засыпая (C8): плата держится на шине
 * (хост читает том или держат кнопку), а со времени прошлого замера прошёл
 * полный интервал. Без этого USB-сессия длиной в сутки давала в архиве
 * дыру на сутки. */
uint8_t Policy_MeasureDue(uint32_t awake_ms, uint32_t interval_ms);
/* Сон кусками для сторожа (A4). IWDG на F401 в STOP не замирает, а его
 * наибольший период — ~32 с при LSI 32 кГц и всего ~22 с при LSI 47 кГц
 * (верх допуска). Час сна он не переживёт, поэтому интервал режется на куски
 * не длиннее kick_sec: RTC будит, сторож получает пинок, и плата сразу
 * засыпает снова — без замера, без PLL, без периферии. Последний кусок —
 * остаток, чтобы интервал между замерами не менялся.
 * Возвращает длину следующего куска сна, 0 — спать больше не нужно. */
uint32_t Policy_SleepChunkSec(uint32_t left_sec, uint32_t kick_sec);

/* Идёт ли счётчик (S1): read(ctx) читается до polls раз, и достаточно одного
 * значения, отличного от первого. Нужно для RTC от LSE: кварц, остановившийся
 * после удачного старта, LSERDY не снимает, и HAL считает его живым; а по
 * RTC_SSR (шаг 1/256 с) видно, что такты не идут. Опрос — счётом, не по
 * тику: правило не должно зависеть от того, что тик сейчас идёт.
 * Возвращает 1 — счётчик изменился, 0 — за все polls чтений стоял. */
typedef uint32_t (*Policy_ReadCounter)(void *ctx);
uint8_t Policy_CounterMoves(Policy_ReadCounter read, void *ctx, uint32_t polls);

/* Причина сброса — в каждую строку CSV. Тихие перезагрузки в поле иначе
 * невидимы: архив растёт, а прибор, может быть, падает каждый час.
 * Биты флагов RCC_CSR (RM0368, 6.3.21) повторены здесь числами, чтобы
 * правило проверялось без CMSIS. */
#define POLICY_CSR_BORRSTF   (1UL << 25)
#define POLICY_CSR_PINRSTF   (1UL << 26)
#define POLICY_CSR_PORRSTF   (1UL << 27)
#define POLICY_CSR_SFTRSTF   (1UL << 28)
#define POLICY_CSR_IWDGRSTF  (1UL << 29)
#define POLICY_CSR_WWDGRSTF  (1UL << 30)
#define POLICY_CSR_LPWRRSTF  (1UL << 31)

/* Код сбоя, который обработчик исключения оставляет в backup-регистре перед
 * сбросом (программным или сторожем): старшие 16 бит — метка (чтобы отличить от мусора и от
 * нуля после потери питания), младшие — что случилось. */
#define POLICY_FAULT_MAGIC   0xFA170000UL
#define POLICY_FAULT_HARD    1U
#define POLICY_FAULT_MEM     2U
#define POLICY_FAULT_BUS     3U
#define POLICY_FAULT_USAGE   4U
#define POLICY_FAULT_NMI     5U
#define POLICY_FAULT_ERROR   6U   /* Error_Handler: отказ инициализации */

/* Колонка reset_cause: биты 0..6 — флаги сброса
 *   1 POR (подача питания), 2 PIN (вывод NRST), 4 BOR (просадка),
 *   8 SFT (программный), 16 IWDG (сторож), 32 WWDG, 64 LPWR;
 * биты 8..11 — код сбоя POLICY_FAULT_*, если обработчик его оставил.
 * Подача питания взводит заодно PIN и BOR — так устроен сброс F401, это
 * не три события. bkp_fault — содержимое backup-регистра как есть. */
uint16_t Policy_ResetCause(uint32_t rcc_csr, uint32_t bkp_fault);

/* Карантин питания датчиков (дизайн v2, ТЗ п. 16).
 *
 * Все датчики сидят на одной рельсе за ключом PB0. Залитый разъём или
 * пробитый датчик каждый час сажает её в ограничение тока LDO — за недели
 * это съедает бюджет, а данных всё равно нет. Отказ рельсы отличаем от
 * отказа одного датчика так: в цикле нет ни воздуха (AHT20), ни почвы
 * (DS18B20) — all_failed. POLICY_QUARANTINE_FAILS таких циклов подряд —
 * питание не подаётся skip_cycles циклов; затем одна попытка: удалась —
 * всё по-старому, нет — снова карантин, то есть одна попытка в M часов.
 *   powered — подавали ли питание в этом цикле (Policy_SensorsPowerAllowed). */
#define POLICY_QUARANTINE_FAILS  3U

typedef struct {
    uint8_t  fails;       /* циклов подряд без воздуха и почвы */
    uint32_t skip_left;   /* сколько ещё циклов не подавать питание */
} Policy_Quarantine;

uint8_t Policy_SensorsPowerAllowed(const Policy_Quarantine *q);
void    Policy_QuarantineUpdate(Policy_Quarantine *q, uint8_t powered,
                                uint8_t all_failed, uint32_t skip_cycles);
/* Можно ли верить часам (A6), колонка time_ok.
 *
 * Внешнего источника времени у прибора нет: часы ставятся на время сборки
 * при прошивке и дальше идут от кварца. VBAT на плате посажен на VDD, так что
 * при замене банки календарь теряется, и часы снова встают на время сборки —
 * может быть, многомесячной давности. Раньше такие строки ничем не
 * отличались от настоящих, и порядок в архиве молча ломался.
 *   sync      — что сделал Time_SyncToBuildIfNeeded;
 *   stored    — отметка, оставленная прошлым стартом (Time_GetTrusted);
 *   archive_read — архив прочитан (том смонтирован, файл открылся или его нет);
 *   last_ts   — метка последней строки архива ("" — строк нет);
 *   build_ts  — время сборки в том же формате.
 * Потеря календаря и самая первая прошивка выглядят одинаково (backup-домен
 * пуст), поэтому их различает архив: если в нём уже есть строки не раньше
 * времени сборки, часы заведомо отстали — не доверять. Метки сравниваются
 * строкой: формат "YYYY-MM-DD hh:mm:ss" упорядочен так же, как время. */
#define POLICY_TIME_SYNC_NONE       0U   /* часы не трогали */
#define POLICY_TIME_SYNC_NEW_BUILD  1U   /* новая сборка, календарь был жив */
#define POLICY_TIME_SYNC_LOST       2U   /* календарь потерян — часы на время сборки */

uint8_t Policy_TimeTrusted(uint8_t sync, uint8_t stored, uint8_t archive_read,
                           const char *last_ts, const char *build_ts);

#endif
