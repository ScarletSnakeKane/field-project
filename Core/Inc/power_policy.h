#ifndef POWER_POLICY_H
#define POWER_POLICY_H

/* Два решения, от которых зависит поведение прибора в поле, — отдельно от HAL.
 *
 * Оба выглядят как одна строка условия и оба уже успели повести себя не так,
 * как задумывалось: одно стирало архив при каждой перепрошивке, второе рвало
 * USB-сессию по таймеру, придуманному для залипшей кнопки. Ошибка в любом из
 * них проявляется редко и молча — данные просто исчезают или файл на хосте
 * оказывается битым, — поэтому правила вынесены сюда и закреплены тестами.
 */

#include <stdint.h>

/* Стирать ли архив при старте.
 *
 * Жест задуман так: удерживать KEY в момент включения. Одной кнопки, однако,
 * мало. Чтобы прошить спящую плату, KEY приходится держать, а программатор в
 * конце делает программный сброс — старт происходит с зажатой кнопкой, и жест
 * срабатывал бы при каждом обновлении прошивки, унося все накопленные данные.
 *
 * Поэтому учитывается ещё и происхождение сброса: программный (флаг SFTRST)
 * означает программатор, а сброс кнопкой RESET или подача питания — намерение
 * пользователя.
 */
uint8_t Policy_ShouldWipeArchive(uint8_t key_held, uint8_t soft_reset);

/* Можно ли уходить в STOP.
 *
 * Уход в сон рвёт USB-сессию и оставляет хосту недочитанный файл, поэтому и
 * зажатая кнопка, и присутствие VBUS означают одно: оставаться на шине.
 *
 * Ограничение по времени намеренно действует ТОЛЬКО на кнопку. Залипшая или
 * залитая водой, она иначе не дала бы уснуть никогда и высадила бы батарею за
 * несколько дней. С USB ровно наоборот: пока кабель воткнут, плата питается от
 * хоста, бодрствование ничего не стоит, и обрывать чтение по таймеру незачем.
 *
 * held_ms — сколько миллисекунд уже длится удержание, hold_max_ms — потолок.
 */
uint8_t Policy_MayEnterSleep(uint8_t key_held, uint8_t usb_present,
                             uint32_t held_ms, uint32_t hold_max_ms);

#endif
