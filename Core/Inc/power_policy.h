#ifndef POWER_POLICY_H
#define POWER_POLICY_H

/* Решения, от которых зависит поведение прибора в поле, — отдельно от HAL.
 *
 * Каждое выглядит как одна строка условия, и каждое уже успело повести себя
 * не так, как задумывалось: кнопочный жест стирал архив при любом аппаратном
 * сбросе (теперь его нет вовсе — архив стирают только с компьютера по USB),
 * таймер залипшей кнопки рвал USB-сессию. Ошибка здесь проявляется редко и
 * молча — данные исчезают или батарея садится, — поэтому правила вынесены
 * сюда и закреплены тестами.
 */

#include <stdint.h>

/* Можно ли уходить в STOP.
 *
 * Уход в сон рвёт USB-сессию и оставляет хосту недочитанный файл, поэтому и
 * зажатая кнопка, и присутствие VBUS означают одно: оставаться на шине.
 *
 * Ограничение по времени намеренно действует ТОЛЬКО на кнопку. Залипшая или
 * залитая водой, она иначе не дала бы уснуть никогда и высадила бы батарею за
 * несколько дней. С USB ровно наоборот: пока кабель воткнут, плата питается от
 * хоста, бодрствование ничего не стоит, и обрывать чтение по таймеру незачем.
 *
 * held_ms — сколько миллисекунд уже длится удержание, hold_max_ms — потолок.
 */
uint8_t Policy_MayEnterSleep(uint8_t key_held, uint8_t usb_present,
                             uint32_t held_ms, uint32_t hold_max_ms);

#endif
