#ifndef AHT20_DECODE_H
#define AHT20_DECODE_H

/* Разбор семи байт ответа AHT20 (статус, 5 байт данных, CRC), отделённый
 * от работы с шиной.
 *
 * Вынесено сюда по той же причине, что и разбор DS18B20: именно в разборе
 * прячется ошибка, которую не видно ни по кодам возврата, ни на осциллографе.
 * Некалиброванный AHT20 честно отвечает на шине — транзакция проходит, бит
 * BUSY снят, — но отдаёт нули. Нули превращаются в -50.00 °C, потому что
 * температура считается как raw/2^20*200 - 50, и такая строка уходила в архив
 * как полноценное измерение.
 */

#include <stdint.h>

typedef enum {
    AHT20_DEC_OK        = 0,
    AHT20_DEC_ERR_BUSY  = 1,  /* измерение ещё не готово */
    AHT20_DEC_ERR_ZERO  = 2,  /* сплошные нули: датчик не откалиброван */
    AHT20_DEC_ERR_RANGE = 3,  /* значение вне шкалы самого датчика: кадр битый */
    AHT20_DEC_ERR_CRC   = 4,  /* контрольная сумма не сошлась: кадр битый */
    AHT20_DEC_ERR_NOCAL = 5,  /* кадр целый, но бит калибровки снят */
} AHT20_DecodeStatus;

/* Шесть байт кадра плюс CRC-8 (полином 0x31, начальное значение 0xFF). */
#define AHT20_FRAME_LEN   7

/* Рабочий диапазон AHT20 по даташиту. Всё, что за ним, датчик не может выдать
 * как результат измерения, поэтому такой кадр — испорченный, а не крайний. */
#define AHT20_TEMP_MIN_C  (-40.0f)
#define AHT20_TEMP_MAX_C  ( 85.0f)

/* Те же границы в сырых единицах: T = raw/2^20*200 - 50, поэтому -40 °C —
 * это raw 52428.8, +85 °C — 707788.8. Берутся ближайшие целые внутри шкалы. */
#define AHT20_RAW_TEMP_MIN  52429UL
#define AHT20_RAW_TEMP_MAX  707788UL

/* CRC-8 кадра AHT20 по даташиту: полином x^8+x^5+x^4+1 (0x31), без отражения,
 * начальное значение 0xFF. */
uint8_t AHT20_CRC8(const uint8_t *data, uint8_t len);

/* Превращает кадр ответа в температуру (°C) и влажность (%).
 * Возвращает AHT20_DEC_OK либо причину отказа; при отказе выходные значения
 * не трогаются. */
AHT20_DecodeStatus AHT20_DecodeFrame(const uint8_t *buf,
                                     float *temp_out, float *hum_out);

#endif
