#ifndef AHT20_DECODE_H
#define AHT20_DECODE_H

/* Разбор шести байт ответа AHT20, отделённый от работы с шиной.
 *
 * Вынесено сюда по той же причине, что и разбор DS18B20: именно в разборе
 * прячется ошибка, которую не видно ни по кодам возврата, ни на осциллографе.
 * Некалиброванный AHT20 честно отвечает на шине — транзакция проходит, бит
 * BUSY снят, — но отдаёт нули. Нули превращаются в -50.00 °C, потому что
 * температура считается как raw/2^20*200 - 50, и такая строка уходила в архив
 * как полноценное измерение.
 */

#include <stdint.h>

typedef enum {
    AHT20_DEC_OK        = 0,
    AHT20_DEC_ERR_BUSY  = 1,  /* измерение ещё не готово */
    AHT20_DEC_ERR_ZERO  = 2,  /* сплошные нули: датчик не откалиброван */
} AHT20_DecodeStatus;

#define AHT20_FRAME_LEN   6

/* Превращает кадр ответа в температуру (°C) и влажность (%).
 * Возвращает AHT20_DEC_OK либо причину отказа; при отказе выходные значения
 * не трогаются. */
AHT20_DecodeStatus AHT20_DecodeFrame(const uint8_t *buf,
                                     float *temp_out, float *hum_out);

#endif
