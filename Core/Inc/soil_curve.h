#ifndef SOIL_CURVE_H
#define SOIL_CURVE_H

/* Пересчёт напряжения ёмкостного датчика влажности в проценты — без HAL и АЦП. */

/* Калибровка: напряжение на сухом воздухе и в воде. Датчик ёмкостный, поэтому
 * зависимость обратная — чем влажнее, тем ниже напряжение. */
#define SOIL_AIR_VOLTS     2.67465f
#define SOIL_WATER_VOLTS   0.87597f

/* Возвращает 0..100. Значения за пределами калибровки прижимаются к границам:
 * почва суше воздуха и мокрее воды физического смысла не имеет, а вот отдать
 * наружу -7 % или 113 % значило бы засорить архив заведомо ложными числами. */
float Soil_VoltageToMoisture(float volts);

#endif
