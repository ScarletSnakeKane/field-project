#ifndef SOIL_CURVE_H
#define SOIL_CURVE_H

/* Пересчёт напряжения ёмкостного датчика влажности в проценты — без HAL и АЦП. */

/* Калибровка: напряжение на сухом воздухе и в воде. Датчик ёмкостный, поэтому
 * зависимость обратная — чем влажнее, тем ниже напряжение. */
#define SOIL_AIR_VOLTS     2.67465f
#define SOIL_WATER_VOLTS   0.87597f

/* Окно правдоподобия: напряжение, которое исправный датчик выдать может.
 * Обрыв питания или сигнала тянет вход АЦП к 0 В (выход датчика разряжается
 * через свой резистор), обрыв земли — к VDD. Без окна прижим ниже превращал
 * оба обрыва в ровные 100 % и 0 % — «только что полили» и «пересохло».
 *
 * Пороги отстоят от калибровки на 0.33..0.48 В (18..27 % шкалы): этого с
 * двойным запасом хватает на уход ёмкостного датчика от температуры и разброс
 * экземпляров (десятки, от силы пара сотен мВ), а шум АЦП — единицы мВ
 * (1 LSB = 0.8 мВ) — на этом фоне вообще не виден. Обе шины питания при этом
 * лежат далеко снаружи окна, так что обрыв в него не попадает. */
#define SOIL_MIN_VALID_VOLTS   0.40f
#define SOIL_MAX_VALID_VOLTS   3.00f

/* Возвращает 0..100 или NAN, если напряжение вне окна правдоподобия (обрыв,
 * замыкание) или само NAN (АЦП не ответил). Внутри окна значения за пределами
 * калибровки прижимаются к границам: почва суше воздуха и мокрее воды
 * физического смысла не имеет, а отдать наружу -7 % или 113 % значило бы
 * засорить архив заведомо ложными числами. */
float Soil_VoltageToMoisture(float volts);

#endif
