#ifndef BATTERY_CURVE_H
#define BATTERY_CURVE_H

/* Пересчёт напряжения банки в проценты заряда — без HAL и без АЦП, чтобы
 * кривую можно было проверять тестами на обычном компьютере. */

#include <stdint.h>

/* Линейный пересчёт «вольты в проценты» для Li-ion даёт грубо неверную картину:
 * почти вся ёмкость лежит в пологом участке 3.9–3.6 В, а края шкалы проскакивают
 * за считанные проценты. Поэтому — таблица с линейной интерполяцией внутри отрезков.
 * Функция монотонна и определена на всей числовой оси: за границами таблицы
 * возвращает 100 и 0 соответственно. */
uint8_t Battery_VoltsToPercent(float v);

/* Процент для замера, которому верить нельзя (NAN на входе). Не 0: ноль в
 * архиве читается как «батарея пуста», то есть как измерение. */
#define BAT_PERCENT_UNKNOWN 255U

/* Делитель напряжения батареи заведён на PA2 = ADC1_IN2.
 * BAT_DIVIDER_RATIO = (R_верх + R_нижн) / R_нижн.
 *
 * Сейчас на плате 10к + 10к, то есть 20 кОм поперёк банки: это ~200 мкА
 * непрерывной утечки при бюджете ~300 мкА на год работы. Замена на 100к + 100к
 * даёт те же 2.0 и снижает утечку до ~21 мкА — коэффициент менять не придётся,
 * время выборки в battery.c уже взято с запасом под высокоомный источник. */
#define BAT_DIVIDER_RATIO   2.0f

/* Заводская калибровка VREFINT снята при VDDA = 3.30 В. */
#define VREFINT_CAL_VDDA    3.30f

/* Окна правдоподобия. VDD ниже 1.8 В — МК уже не работает, выше 3.6 В —
 * за абсолютным максимумом: такое VDD значит, что испорчен замер опоры.
 * Банка 18650 живёт в 2.5..4.4 В; 0 В (оборван верх делителя) и ~6.6 В
 * (оборван низ) — это обрыв, а не «пусто» и «полно». */
#define BAT_VDD_MIN         1.80f
#define BAT_VDD_MAX         3.60f
#define BAT_VOLTS_MIN       2.50f
#define BAT_VOLTS_MAX       4.40f

/* Пересчёт сырых отсчётов АЦП в VDD и напряжение банки.
 * raw_bat и raw_ref — 12-битные отсчёты канала батареи и VREFINT,
 * vrefint_cal — заводская калибровка VREFINT при VREFINT_CAL_VDDA.
 * Возвращает 1 и оба значения, если замер правдоподобен; иначе 0, а в
 * *volts_out — NAN, чтобы отказ не выглядел измерением. *vdd_out при отказе
 * — NAN, только если неправдоподобна сама опора; если опора в окне, VDD
 * отдаётся и при банке вне шкалы: по нему хранилище решает, можно ли писать. */
uint8_t Battery_ComputeVolts(uint32_t raw_bat, uint32_t raw_ref, uint16_t vrefint_cal,
                             float *vdd_out, float *volts_out);

#endif
